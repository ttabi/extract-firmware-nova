# Extract the GSP-RM binaries and create the TLV files for each GPU that has its own
# .fwsignature section.
def gsprm(tu10x_gsp_src, ga10x_gsp_src):
    global outputpath

    fwimage_from_gsp_elf(tu10x_gsp_src, "tu102")
    fwimage_from_gsp_elf(ga10x_gsp_src, "ga102")

    elf = ELF64(tu10x_gsp_src)
    gsp_tlv_from_elf(elf, ".fwsignature_tu10x", "tu102")
    gsp_tlv_from_elf(elf, ".fwsignature_tu11x", "tu116")
    gsp_tlv_from_elf(elf, ".fwsignature_ga100", "ga100")

    elf = ELF64(ga10x_gsp_src)
    gsp_tlv_from_elf(elf, ".fwsignature_ga10x", "ga102")
    gsp_tlv_from_elf(elf, ".fwsignature_ad10x", "ad102")
    gsp_tlv_from_elf(elf, ".fwsignature_gh100", "gh100")
    gsp_tlv_from_elf(elf, ".fwsignature_gb10x", "gb100")
    gsp_tlv_from_elf(elf, ".fwsignature_gb20x", "gb202")

    # GB20x is unique in that gsp.tlv has some differences
    # among the GPU variants, so we need to create unique
    # files for all of them.
    for gpu in ["gb203", "gb205", "gb206", "gb207"]:
        gsp_tlv_from_elf(elf, ".fwsignature_gb20x", gpu)

    if "gb10b" in supported:
        gsp_tlv_from_elf(elf, ".fwsignature_gb10y", "gb10b")
    if "gb20b" in supported:
        gsp_tlv_from_elf(elf, ".fwsignature_gb20y", "gb20b")
    if "gr100" in supported:
        gsp_tlv_from_elf(elf, ".fwsignature_gr10x", "gr100")

# Extract the GSP-RM firmware from the .run file and copy the binaries
# to the target directory.
def gsp_firmware_from_run(filename):
    with tempfile.TemporaryDirectory() as temp:
        directory = extract_run_file(filename, temp)

        tu10x_gsp_src = os.path.join(directory, "gsp_tu10x.bin")
        ga10x_gsp_src = os.path.join(directory, "gsp_ga10x.bin")

        gsprm(tu10x_gsp_src, ga10x_gsp_src)
        ucodes(directory)

# Extract GSP firmware from a local build output directory.
# This is an NVIDIA-internal feature for use with internal build systems.
def gsp_firmware_from_build(gsp_build_dir):
    if not os.path.isdir(gsp_build_dir):
        raise MyException(f"GSP build directory does not exist: {gsp_build_dir}")

    tu10x_gsp_src = os.path.join(gsp_build_dir, "gsp_tu10x.bin")
    ga10x_gsp_src = os.path.join(gsp_build_dir, "gsp_ga10x.bin")

    if not os.path.exists(tu10x_gsp_src) or not os.path.exists(ga10x_gsp_src):
        raise MyException(f"Firmware files are missing in {gsp_build_dir}")

    gsprm(tu10x_gsp_src, ga10x_gsp_src)
    ucodes(gsp_build_dir)

# Find the .run file and extract the GSP-RM binaries from it.
#
# `pathspec` is either
# 1) empty string -- determine the URL to download the .run file that matches the current OpenRM tree
# 2) url -- download the .run file from that URL
# 3) filename -- use the specific filename
# 4) path -- extract the binaries from the local build
def driver(pathspec):
    global version

    if pathspec == "":
        # No path/url provided, so make a guess of the URL
        # to automatically download the right version.
        pathspec = f"https://download.nvidia.com/XFree86/Linux-x86_64/{version}/NVIDIA-Linux-x86_64-{version}.run"

    if re.search("^https?://", pathspec):
        with tempfile.NamedTemporaryFile(prefix = f"NVIDIA-Linux-x86_64-{version}-", suffix = ".run") as f:
            print(f"Downloading driver from {pathspec} as {f.name}")
            try:
                urllib.request.urlretrieve(pathspec, f.name)
            except urllib.error.HTTPError as e:
                if e.code == 404:
                    raise MyException(f"Driver version {version} not found at download.nvidia.com.")
                raise MyException(f"Failed to download {pathspec}: HTTP {e.code} {e.reason}")
            except urllib.error.URLError as e:
                raise MyException(f"Failed to download {pathspec}: {e.reason}")

            gsp_firmware_from_run(f.name)
    elif os.path.isfile(pathspec) and os.access(pathspec, os.R_OK):
        gsp_firmware_from_run(pathspec)
    elif os.path.isdir(pathspec):
        gsp_firmware_from_build(pathspec)
    else:
        raise MyException(f"{pathspec} does not exist or is unreadable.")

# Two kinds of symlinks are created by the script: a symlink from one firmware file
# for one GPU to the matching file for another GPU, or a symlink from the directory
# of one GPU variant to its primary (e.g. GB203 -> GB202).
# This function standardizes the process of making those links.

# When linking one GPU to another, Nouveau compatibility must be considered.  For
# Turing and Ampere, Nouveau created multiple subdirectories for each GPU that
# includes non-GSP firmware files.  These other directories must not be touched.
def link_gpu(dest_gpu: str, src_gpu: str, filename: str | None = None):
    global outputpath
    global nvidiadir
    global subdir

    if filename:
        # We only support linking files to the same filename in another directory.
        src = os.path.join(outputpath, "nvidia", nvidiadir, src_gpu, subdir, filename)
        dest = os.path.join(outputpath, "nvidia", nvidiadir, dest_gpu, subdir, filename)
        os.makedirs(os.path.join(outputpath, "nvidia", nvidiadir, src_gpu, subdir), exist_ok = True)
        symlink(dest, src, target_is_directory = False)
    else:
        # Directory symlinks can only be between GPU variants.
        if src_gpu[:2] != dest_gpu[:2]:
            raise MyException(f"Cannot link {src_gpu} to {dest_gpu}")

        # Set to True if the directory hierarchy also has Nouveau binaries in it
        # that might conflict.
        has_nouveau = nvidiadir == ""

        if has_nouveau and src_gpu.startswith(("tu", "ga")):
            src = os.path.join(outputpath, "nvidia", nvidiadir, src_gpu, subdir)
            dest = os.path.join(outputpath, "nvidia", nvidiadir, dest_gpu, subdir)
            os.makedirs(os.path.join(outputpath, "nvidia", nvidiadir, src_gpu), exist_ok = True)
        else:
            src = os.path.join(outputpath, "nvidia", nvidiadir, src_gpu)
            dest = os.path.join(outputpath, "nvidia", nvidiadir, dest_gpu)

            # If the source is an existing real directory, then create symlinks to
            # all the individual files in the target instead.  For some GPUs, the
            # script will create some unique files, and leave it to this function
            # to create symlinks for the rest.
            if os.path.isdir(src) and not os.path.islink(src):
                for d in os.listdir(os.path.join(dest, subdir)):
                    # Leave alone the files the source generated for itself
                    if not os.path.exists(os.path.join(src, subdir, d)):
                        link_gpu(dest_gpu, src_gpu, d)
                return

        symlink(dest, src, target_is_directory = True)

# Create symlinks in the target directory for the other GPUs.  This mirrors
# what the WHENCE file in linux-firmware does.
def symlinks():
    global outputpath
    global nvidiadir
    global subdir
    from pathlib import Path

    topdir = os.path.join(outputpath, "nvidia", nvidiadir)
    print(f"Creating symlinks in {topdir}")

    # Nouveau supports Turing and Ampere without GSP-RM support, using separate firmware
    # files in the 'acr', 'gr', 'nvdec', and 'sec2' subdirectories, which are all
    # siblings of the 'gsp' subdirectory.  Therefore, for these GPUs, we must symlink
    # from <gpu1>/gsp/ -> <gpu2>/gsp instead of just <gpu1> -> <gpu2>.

    # Turing / GA100
    for d in ["tu104", "tu106"]:
        link_gpu("tu102", d)

    for d in ["tu117"]:
        link_gpu("tu116", d)

    # TU11x uses the same GSP bootloader as TU10x
    link_gpu("tu102", "tu116", "gsp_bootloader.tlv")

    # TU11x and GA100 use the same generic bootloader as TU10x
    link_gpu("tu102", "tu116", "gen_bootloader.tlv")
    link_gpu("tu102", "ga100", "gen_bootloader.tlv")

    # Symlink the GSP-RM image for TU11x and GA100
    link_gpu("tu102", "tu116", "gsp.bin")
    link_gpu("tu102", "ga100", "gsp.bin")

    # Ampere
    for d in ["ga103", "ga104", "ga106", "ga107"]:
        link_gpu("ga102", d)

    # Ada
    for d in ["ad103", "ad104", "ad106", "ad107"]:
        link_gpu("ad102", d)

    # Blackwell
    for d in ["gb102"]:
        link_gpu("gb100", d)

    for d in ["gb203", "gb205", "gb206", "gb207"]:
        link_gpu("gb202", d)

    # Rubin
    if os.path.exists(os.path.join(topdir, "gr100")):
        for d in ["gr102"]:
            link_gpu("gr100", d)

    # Handle gsp.bin for all remaining paths.
    root = Path(topdir)
    paths = [d.name for d in root.glob("*")
             if os.path.isdir(os.path.join(topdir, d, subdir))
             and not os.path.exists(os.path.join(topdir, d, subdir, "gsp.bin"))]
    for d in paths:
        link_gpu("ga102", d, "gsp.bin")

    # Symlink the ucodes binaries, if they exist.
    if os.path.exists(os.path.join(topdir, "tu102", subdir, "ucodes.bin")):
        for d in ["tu116", "ga100"]:
            link_gpu("tu102", d, "ucodes.bin")
            link_gpu("tu102", d, "ucodes.tlv")

    if os.path.exists(os.path.join(topdir, "ga102", subdir, "ucodes.bin")):
        paths = [d.name for d in root.glob("*")
                 if os.path.isdir(os.path.join(topdir, d, subdir))
                 and not os.path.exists(os.path.join(topdir, d, subdir, "ucodes.bin"))
                 and d.name != "ga102"]
        for d in paths:
            link_gpu("ga102", d, "ucodes.bin")
            link_gpu("ga102", d, "ucodes.tlv")

    # Verify that there are no broken symlinks, and that every file
    # symlink points to a file inside a gsp/ directory.
    for dirpath, dirnames, filenames in os.walk(topdir):
        for name in dirnames + filenames:
            full = os.path.join(dirpath, name)
            if not os.path.islink(full):
                continue
            target = os.readlink(full)
            if not os.path.exists(full):
                print(f"Warning: broken symlink {full} -> {target}")
                continue
            # Directory symlinks (e.g. tu104/gsp -> ../tu102/gsp,
            # ad103 -> ad102) are exempt.
            if os.path.isdir(full):
                continue
            resolved = os.path.normpath(os.path.join(dirpath, target))
            if subdir and os.path.basename(os.path.dirname(resolved)) != subdir:
                print(f"Warning: symlink {full} -> {target} does not point to a file in a '{subdir}' directory")

    # Verify that we have the necessary files or links for every GPU.
    for d in [entry.name for entry in os.scandir(topdir) if entry.is_dir()]:
        if not os.path.exists(os.path.join(topdir, d, subdir, "gsp.bin")):
            print(f"Warning: {os.path.join(topdir, d, subdir, 'gsp.bin')} is missing")
        if not os.path.exists(os.path.join(topdir, d, subdir, "gsp.tlv")):
            print(f"Warning: {os.path.join(topdir, d, subdir, 'gsp.tlv')} is missing")
        if os.path.islink(os.path.join(topdir, d, subdir, "gsp.tlv")):
            print(f"Warning: {os.path.join(topdir, d, subdir, 'gsp.tlv')} should not be a symlink")
        if not os.path.exists(os.path.join(topdir, d, subdir, "gsp_bootloader.tlv")):
            print(f"Warning: {os.path.join(topdir, d, subdir, 'gsp_bootloader.tlv')} is missing")

        has_load = os.path.exists(os.path.join(topdir, d, subdir, "booter_load.tlv"))
        has_unload = os.path.exists(os.path.join(topdir, d, subdir, "booter_unload.tlv"))
        has_fmc = os.path.exists(os.path.join(topdir, d, subdir, "fmc.tlv"))
        if has_load != has_unload:
            print(f"Warning: {os.path.join(topdir, d, subdir)}/ booter_load requires booter_unload, and vice versa")
        if not has_load and not has_fmc:
            print(f"Warning: {os.path.join(topdir, d, subdir)}/ must have booter or fmc")
        if has_load and has_fmc:
            print(f"Warning: {os.path.join(topdir, d, subdir)}/ must not have both booter and fmc")

    # Verify that we have entries for each supported gpu
    for gpu in supported:
        if not os.path.exists(os.path.join(topdir, gpu, subdir, "gsp.bin")):
            print(f"Warning: {os.path.join(topdir, gpu, subdir, 'gsp.bin')} is missing")
        if not os.path.exists(os.path.join(topdir, gpu, subdir, "gsp.tlv")):
            print(f"Warning: {os.path.join(topdir, gpu, subdir, 'gsp.tlv')} is missing")
        if not os.path.exists(os.path.join(topdir, gpu, subdir, "gsp_bootloader.tlv")):
            print(f"Warning: {os.path.join(topdir, gpu, subdir, 'gsp_bootloader.tlv')} is missing")

        has_load = os.path.exists(os.path.join(topdir, gpu, subdir, "booter_load.tlv"))
        has_unload = os.path.exists(os.path.join(topdir, gpu, subdir, "booter_unload.tlv"))
        has_fmc = os.path.exists(os.path.join(topdir, gpu, subdir, "fmc.tlv"))
        if has_load != has_unload:
            print(f"Warning: {os.path.join(topdir, gpu, subdir)}/ booter_load requires booter_unload, and vice versa")
        if not has_load and not has_fmc:
            print(f"Warning: {os.path.join(topdir, gpu, subdir)}/ must have booter or fmc")
        if has_load and has_fmc:
            print(f"Warning: {os.path.join(topdir, gpu, subdir)}/ must not have both booter and fmc")

    # Verify that the gsp.tlv for each GPU has the correct TLV values for that GPU.  This
    # catches situations where one GPU is symlinked to another, but shouldn't be.
    for gpu in supported:
        filename = os.path.join(topdir, gpu, subdir, "gsp.tlv")
        if not os.path.exists(filename):
            continue

        entries = read_tlv(filename)
        for tag, field in hal_tlv_tags.items():
            if tag not in entries:
                print(f"Warning: {os.path.join(gpu, subdir, 'gsp.tlv')} has no '{tag}' entry")
                continue
            # Integer entries are written little-endian, as four or eight bytes
            # depending on magnitude.
            value = int.from_bytes(entries[tag], "little")
            if value != hal_value(field, gpu):
                print(f"Warning: {os.path.join(gpu, subdir, 'gsp.tlv')} tag {tag} value of {value} should be {hal_value(field, gpu)}")

# Create a text file that can be inserted as-is to the WHENCE file of the linux-firmware
# git repository.
#
# Traverse the outputpath and build a WHENCE file from it.  This ensures that WHENCE file
# always matches the real world.  The drawback is that it requires the -d and -s options
# to get a full picture.

# We must also maintain compatibility with the existing directory hierarchy that is
# defined by Nouveau, which is why ga103/gsp -> ga102/gsp, but ad103 -> ad102.
#
# Some hard rules for the layout of files:
#  1. No file of any version can symlink to a file of a different version,
#     even if the files are identical.  This allows distros to ship each version
#     independently.  Note that this does not really apply to TLV files, but
#     the restriction is still valid.
#  2. All files must be located in the /gsp/ subdirectory of the GPU directory,
#     and there must be no symlinks to any files outside of the /gsp/ directory.
#     This allows the Nova driver to find all of the files it needs inside
#     the /gsp/ directory.
#  3. Replacing a file/directory with a symlink (or vice versa) is strongly
#     discouraged.  Many distros cannot handle this transition.
#  4. Ideally, this file should only change when adding support for new GPUs,
#     because newer versions of firmware images should have the same filenames
#     as previous versions.
def whence():
    global outputpath

    whence = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(outputpath, "nvidia")):  # followlinks=False by default
        # Regular files and symlinks-to-files both land in filenames
        for name in filenames:
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, outputpath)
            if os.path.islink(full):
                whence.append(f"Link: {rel} -> {os.readlink(full)}\n")
            else:
                whence.append(f"File: {rel}\n")
        # Symlinks-to-directories land in dirnames; with followlinks=False
        # os.walk lists them but won't recurse into them, so capture them here.
        for name in dirnames:
            full = os.path.join(dirpath, name)
            if os.path.islink(full):
                whence.append(f"Link: {os.path.relpath(full, outputpath)} -> {os.readlink(full)}\n")

    whence = sorted(whence, key=lambda s: s.split()[1])

    with open(os.path.join(outputpath, "WHENCE.txt"), "w") as f:
        f.writelines(whence)

    print(f"Created {os.path.join(outputpath, 'WHENCE.txt')}")

# ArgumentParser filter for alphanumeric parameters.
def alphanumeric(value: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9]*", value):
        raise argparse.ArgumentTypeError("must contain only alphanumeric characters")

    return value

def main():
    global outputpath
    global version
    global nvidiadir
    global subdir
    global hals

    parser = argparse.ArgumentParser(
        allow_abbrev = False,
        description = "Extract firmware binaries from the OpenRM git repository"
        " in a format expected by the Nova device drivers.",
        epilog = "Running as root and specifying -o /lib/firmware will install"
        " the firmware files directly where Nova expects them."
        " The --revision option is useful for testing new firmware"
        " versions without changing Nova source code."
        " The --driver option accepts a .run file path, a URL, or a local"
        " build output directory.  If -d is given with no argument, the .run"
        " file is downloaded automatically.")
    parser.add_argument("-i", "--input", default = os.getcwd(),
        help = "Path to source directory (where version.mk exists)")
    parser.add_argument("-o", "--output", default = None,
        help = "Path to target directory (where files will be written)")
    parser.add_argument("-r", "--revision",
        help = "Files will be named with this version number.")
    parser.add_argument("--debug-fused", action="store_true",
        help = "Extract debug instead of production images.")
    parser.add_argument("-d", "--driver",
        nargs = "?", const = "",
        help = "Also extract GSP-RM firmware from a source."
        " A URL or path to a .run driver package downloads or extracts it."
        " A path to a local build output directory (e.g."
        " drivers/resman/build/gsp/_out/Linux_amd64_release) copies"
        " the GSP firmware directly.  If -d is given with no argument,"
        " the .run file is downloaded automatically.")
    parser.add_argument("-s", "--symlink", action="store_true",
        help = "Also create symlinks for all supported GPUs.  Requires -d option.")
    parser.add_argument("-w", "--whence", action="store_true",
        help = "Also generate a WHENCE file.  Requires -d and -s options.")
    parser.add_argument("--nvidiadir", default = nvidiadir, type = alphanumeric,
        help = "Output directory top-level path, i.e. /lib/firmware/nvidia/{nvidiadir}/<gpu>/."
        " Default: '%(default)s'")
    parser.add_argument("--subdir", default = subdir, type = alphanumeric,
        help = "Output directory bottom-level path, i.e. /lib/firmware/nvidia/.../<gpu>/{subdir}."
        " Default: '%(default)s'")

    # Undocumented, dangerous option. If set, this will blindly erase the target directory.
    # For example, `-o /lib/firmware --clean` will trash your /lib/firmware and make your system
    # unbootable.  For safety, this requires the -o option.
    parser.add_argument("--clean", action = "store_true", help = argparse.SUPPRESS)

    args = parser.parse_args()

    if args.symlink and args.driver is None:
        parser.error("-s/--symlink requires -d/--driver")
    if args.whence and (args.driver is None or not args.symlink):
        parser.error("-w/--whence requires both -d/--driver and -s/--symlink")

    if args.clean and args.output is None:
        parser.error("--clean requires -o/--output")

    outputpath = os.path.abspath(args.output or os.path.join(os.getcwd(), "_out"))

    # Symlinks should not be created in the linux-firmware git repository, because
    # it uses the WHENCE file to create symlinks.  Check for that, to avoid
    # accidental usage that is confusing.
    if args.symlink and os.path.exists(os.path.join(outputpath, "copy-firmware.sh")):
        raise MyException("Symlinks should not be created in the linux-firmware repository")

    # If args.driver is a file or path, normalize it before the chdir.
    if args.driver and not re.search("^https?://", args.driver):
        args.driver = os.path.abspath(args.driver)

    args.input = os.path.abspath(args.input)
    os.chdir(args.input)

    if not os.path.isfile("version.mk"):
        raise MyException(f"Source directory {args.input} is incorrect")

    version = args.revision
    if not version:
        with open("version.mk") as f:
            m = re.search(r"^NVIDIA_VERSION = ([^\s]+)", f.read(), re.MULTILINE)
            if not m:
                raise MyException("Could not find or parse NVIDIA_VERSION from version.mk")
            version = m.group(1)

    if not version.isascii():
        raise MyException(f"Version string {version} must not contain non-ASCII characters")

    nvidiadir = args.nvidiadir
    subdir = args.subdir

    print(f"Generating files for version {version}")

    print(f"Writing files to {outputpath}")
    if os.path.isdir(outputpath) and os.listdir(outputpath):
        print("Warning: directory already exists and is not empty")

    if args.clean:
        # Aggressively try to delete the output directory.
        try:
            os.remove(outputpath)
        except OSError:
            pass
        shutil.rmtree(outputpath, ignore_errors = True)

        if os.path.lexists(outputpath):
            raise MyException(f"Could not delete {outputpath}")

    os.makedirs(outputpath, exist_ok = True)

    # GB10B (Jetson Thor) support was added in r580
    if is_supported("gb10b"):
        supported.append("gb10b")

    # GB20B (N1X) support was added in r580
    if is_supported("gb20b"):
        supported.append("gb20b")

    # GR100 support was added in r610
    if is_supported("gr100"):
        supported.extend(["gr100", "gr102"])

    # The generic bootloader is only defined for TU102 but is used
    # by all TU1xx and GA100.
    generic_bootloader("tu102")

    booter("tu102", "load", 16, args.debug_fused)
    booter("tu102", "unload", 16, args.debug_fused)
    # TU10x and GA100 do not have debug-fused versions of the GSP bootloader
    gsp_bootloader("tu102")

    booter("tu116", "load", 16, args.debug_fused)
    booter("tu116", "unload", 16, args.debug_fused)
    # TU11x uses the same bootloader as TU10x

    booter("ga100", "load", 384, args.debug_fused)
    booter("ga100", "unload", 384, args.debug_fused)
    gsp_bootloader("ga100")

    booter("ga102", "load", 384, args.debug_fused)
    booter("ga102", "unload", 384, args.debug_fused)
    gsp_bootloader("ga102", args.debug_fused)

    booter("ad102", "load", 384, args.debug_fused)
    booter("ad102", "unload", 384, args.debug_fused)
    gsp_bootloader("ad102", args.debug_fused)
#    scrubber("ad102", 384, args.debug_fused) # Not currently used by Nova

    gsp_bootloader("gh100", args.debug_fused)
    fmc("gh100", args.debug_fused)

    gsp_bootloader("gb100", args.debug_fused)
    fmc("gb100", args.debug_fused)

    gsp_bootloader("gb202", args.debug_fused)
    fmc("gb202", args.debug_fused)

    if "gb10b" in supported:
        gsp_bootloader("gb10b", args.debug_fused)
        fmc("gb10b", args.debug_fused)

    if "gb20b" in supported:
        gsp_bootloader("gb20b", args.debug_fused)
        fmc("gb20b", args.debug_fused)

    if "gr100" in supported:
        gsp_bootloader("gr100", args.debug_fused)
        fmc("gr100", args.debug_fused)

    # Extract gsp.bin and create gsp.tlv
    if args.driver is not None:
        # We only need to read the HALs if we're generating gsp.tlv

        # Search for the new NVoC variables, which were added in r630.
        # This may pick up variables we don't care about, depending
        # on the OpenRM version.
        # Note: g_gpu_arch_nvoc.c was added in r580
        hals2 = parse_nvoc_hals("src/nvidia/generated/g_gpu_arch_nvoc.c", hals)
        if "gspFwHeapBaseSize" in hals2:
            print("Generating GSP-RM TLV variables from NVOC source files")
            update_hals(hals2)
        else:
            # For older versions of OpenRM, scrape other files to build the
            # variables so that they mimic what g_gpu_arch_nvoc.c would
            # contain if it were complete.
            hals2 = parse_legacy_hals()
            if hals2:
                print("Generating GSP-RM TLV variables from legacy source files")
                update_hals(hals2)

        # print_hals(hals)
        driver(args.driver)

    if args.symlink:
        symlinks()

    if args.whence:
        whence()

if __name__ == "__main__":
    try:
        main()
    except MyException as e:
        # The full stack trace is too noisy with MyException
        print(f"Error: {e}", file=sys.stderr)

        # os._exit() reports the failure without raising SystemExit the way sys.exit()
        # would, but it also skips the flush that the interpreter would otherwise do on
        # the way out.  Stdout is block buffered whenever it is not a terminal, so it has
        # to be flushed by hand or a redirected run loses the output leading up to the
        # failure.
        #
        # The flush can itself fail, on a broken pipe from something like "| head" or on a
        # full disk.  That exception would escape this handler, burying the message above
        # in a traceback and exiting 120 rather than 1.  Ignore all of them rather than
        # just OSError, because the response is the same whatever the reason: if the
        # output cannot be written then there is nothing left to report it with, and the
        # process is about to exit non-zero regardless.
        try:
            sys.stdout.flush()
            sys.stderr.flush()
        except:
            pass

        os._exit(1)
