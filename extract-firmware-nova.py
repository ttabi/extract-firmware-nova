# RM autogenerates per-chip "Hal field" assignments in files such as g_gpu_arch_nvoc.c.
# Each field is initialized with an if / else-if / else chain, where every if-branch
# annotates its (possibly multi-line) condition with a "/* ChipHal: GPU1 | GPU2 | ... */"
# comment listing the GPUs the branch applies to, and the trailing else is a catch-all
# default.  Fields that do not vary by chip are instead assigned unconditionally, with no
# if / else chain.  This parses one such field and returns a dictionary mapping each GPU
# name (as it appears in the comment, e.g. "TU102") to the value expression assigned for
# that GPU.  The catch-all default value is stored under the None key.

# pcpp's evaluator holds no state between calls, so one instance serves every call.  It
# returns an int subclass that additionally tracks whether the value is unsigned.
c_expression_evaluator = Evaluator()

# Parse a C integer constant expression and return its value.  Handles plain constants,
# hex ("0x..."), and arbitrary arithmetic, bitwise, and conditional expressions, such as
# "((22U << 20) + (32U << 20) + ((48U << 10) * 2048U))" or the expansion of an NV_MAX,
# "(((17485824) > (17482752)) ? (17485824) : (17482752)) + 4096U".  Every name in the
# expression must already be expanded, apart from the NvBool constants handled below.
def parse_c_value(value: str) -> int | bool:
    # Make a guess as to whether the expression is boolean or not.  This is imperfect,
    # and may need to be changed for future versions of OpenRM, because booleans and
    # integers are interchangeable in C.  For now, assume that any expression with
    # boolean macros in it is also boolean.  This breaks on ternary expressions like
    # "NV_TRUE ? x : y" however.
    is_bool = any(s in value for s in ("(NvBool)", "NV_TRUE", "NV_FALSE"))
    expression = value.replace("(NvBool)", "")

    try:
        result = c_expression_evaluator(expression,
                                        identifiers = {"NV_TRUE": 1, "NV_FALSE": 0}).value()
    except SyntaxError as e:
        raise MyException(f"Cannot evaluate C expression '{value}': {e}")

    # This should catch expressions where we miscalculate is_bool.
    if is_bool and result not in (0, 1):
        raise MyException(f"Invalid boolean expression '{value}'")

    return bool(result) if is_bool else result

# Walk the brace-delimited branch bodies of the single if / else-if / else statement that
# begins at 'start' and return the offset just past its final '}'.  The chain continues
# only while a closing brace is followed by another "else".  Branch conditions contain
# only parentheses and bodies contain a single statement, so the only braces in the
# statement are the ones that delimit each body.
def nvoc_chain_end(text: str, start: int, what: str, filename: str) -> int:
    pos = start

    while True:
        open_brace = text.find("{", pos)
        if open_brace == -1:
            raise MyException(f"Malformed {what} in {filename}")
        # Branch bodies are never nested, so the body ends at the next '}'.
        close_brace = text.find("}", open_brace)
        if close_brace == -1:
            raise MyException(f"Malformed {what} in {filename}")
        pos = close_brace + 1
        # Skip whitespace and "// ..." comments to see if another branch follows.
        if not re.match(r"(?:\s|//[^\n]*\n)*else\b", text[pos:]):
            return pos

# Parse an NVOC-generated file and extract all of the HAL variables into a nested
# dictionary.  The outer dictionary is keyed by variable name, and each of its values is
# an inner dictionary that maps each GPU to the value the variable has there.  A variable
# that does not vary by chip has the same value recorded for every GPU in `supported`.
#
# `required` names the variables this caller goes on to read.  Those must cover every GPU
# in `supported` if the file defines them at all, because a partially covered variable
# would otherwise be read as a zero or a KeyError further down.  A generated file holds
# many variables besides the ones we want, so anything outside `required` is returned
# with whatever coverage it happens to have rather than failing the run.
def parse_nvoc_hals(filename, required) -> dict:
    if not os.path.exists(filename):
        return {}

    with open(filename) as f:
        text = f.read()

    pattern = re.compile(r"^[ \t]*//[ \t]*Hal field --[ \t]*([a-zA-Z]+)[ \t]*\n", re.MULTILINE)
    hals2 = {}

    for marker in pattern.finditer(text):
        variable = marker.group(1)

        # Fields that have the same value on every chip are assigned unconditionally, with
        # no if / else chain at all, so the value is the catch-all default.
        unconditional = re.compile(rf"\s*pThis->{variable}\s*=\s*(.*?);", re.DOTALL)
        assignment = unconditional.match(text, marker.end())
        if assignment:
            hals2[variable] = {}
            value = parse_c_value(assignment.group(1))
            for gpu in supported:
                hals2[variable][gpu] = value
            continue

        # Otherwise the field is initialized by a single if / else-if / else statement that
        # begins right after the marker.
        block = text[marker.end():nvoc_chain_end(text, marker.end(),
                                                 f"Hal field '{variable}'", filename)]

        field = {}
        # Each if / else-if branch ends its condition with a "/* ChipHal: GPU1 | GPU2 | ... */"
        # comment, immediately followed by a "{ pThis-><variable> = <value>; }" body.
        # re.DOTALL lets both the GPU list and the value span multiple lines.  The GPU list
        # is matched as chip names, separators and whitespace rather than as ".*?", so that
        # a branch whose body holds no assignment cannot be bridged over: "." would happily
        # run past the closing "*/" and swallow the following branch's first GPU.
        branch = re.compile(
            rf"/\*\s*ChipHal:\s*([\w\s|]+?)\s*\*/\s*"
            rf"\{{\s*pThis->{variable}\s*=\s*(.*?);\s*\}}",
            re.DOTALL)
        for gpus, value in branch.findall(block):
            for gpu in gpus.split("|"):
                gpu = gpu.strip().lower()
                if gpu in supported:
                    field[gpu] = parse_c_value(value)

        # The trailing "// default" / else branch is the catch-all.
        default = re.search(
            rf"//\s*default\s*else\s*\{{\s*pThis->{variable}\s*=\s*(.*?);\s*\}}",
            block, re.DOTALL)
        if default:
            value = parse_c_value(default.group(1))
            for gpu in supported:
                field.setdefault(gpu, value)

        if variable in required and len(field) != len(supported):
            raise MyException(f"Expected {len(supported)} GPUs for '{variable}' in {filename} but found {len(field)}")

        hals2[variable] = field

    return hals2

# Inline HAL bodies for each NVOC header, keyed by file name, so that a header holding
# several halified methods is only scanned once.
nvoc_inline_bodies_cache = {}

# NVOC emits the simplest HAL implementations as inline functions in the generated
# header, as in
#
#   static inline NvU32 kpmuReservedMemoryBackingStoreSizeGet_bdab1d(struct KernelPmu *pKernelPmu){
#       return 9437184;
#   }
#
# Return a dictionary mapping every such function name to its return expression.  An
# implementation that is a real function in a .c file has no entry here.
def nvoc_inline_bodies(filename: str) -> dict:
    if filename in nvoc_inline_bodies_cache:
        return nvoc_inline_bodies_cache[filename]

    with open(filename) as f:
        text = f.read()

    pattern = re.compile(
        r"static\s+inline\s+\w+\s+(\w+)\s*\([^)]*\)\s*\{\s*return\s+(.*?);\s*\}", re.DOTALL)
    bodies = dict(pattern.findall(text))

    nvoc_inline_bodies_cache[filename] = bodies
    return bodies

# A halified method is dispatched through a function pointer that NVOC assigns with the
# same if / else-if / else chain it uses for Hal fields, except that each branch body
# stores an implementation instead of a value:
#
#   // kpmuReservedMemoryBackingStoreSizeGet -- halified (3 hals) body
#   if (...) /* ChipHal: GR100 | GR102 */
#   {
#       pThis->__kpmuReservedMemoryBackingStoreSizeGet__ = &kpmuReservedMemoryBackingStoreSizeGet_3c0c39;
#   }
#
# Return a dictionary mapping every GPU in `supported` to the name of the implementation
# the method resolves to on that chip, or an empty dictionary if the method is not halified
# in this source tree.
#
# NVOC nests this chain inside an RmVariantHal test, and emits branches with no assignment
# at all ("// NVOC_UNREACHABLE, NULL-initialized.") for chips that cannot reach the method.
# Both are handled: nvoc_chain_end() walks through the nesting, and the GPU list is matched
# as chip names rather than as ".*?" so an assignment-less branch cannot be bridged over.
def parse_nvoc_hal_dispatch(c_filename: str, method: str) -> dict:
    if not os.path.exists(c_filename):
        return {}

    with open(c_filename) as f:
        text = f.read()

    marker = re.search(rf"^[ \t]*//[ \t]*{method}[ \t]*--[ \t]*halified[^\n]*\n",
                       text, re.MULTILINE)
    if not marker:
        return {}

    block = text[marker.end():nvoc_chain_end(text, marker.end(),
                                             f"HAL method '{method}'", c_filename)]

    field = {}
    branch = re.compile(
        rf"/\*\s*ChipHal:\s*([\w\s|]+?)\s*\*/\s*"
        rf"\{{\s*pThis->__{method}__\s*=\s*&(\w+);\s*\}}",
        re.DOTALL)
    for gpus, implementation in branch.findall(block):
        for gpu in gpus.split("|"):
            gpu = gpu.strip().lower()
            if gpu in supported:
                field[gpu] = implementation

    # The trailing else is the catch-all.  Unlike a Hal field, NVOC only labels it
    # "// default" when the method declares an explicit default implementation, so match
    # the else itself rather than the comment.
    default = re.search(rf"else\s*\{{\s*pThis->__{method}__\s*=\s*&(\w+);\s*\}}\s*$",
                        block.rstrip())
    if default:
        for gpu in supported:
            field.setdefault(gpu, default.group(1))

    if len(field) != len(supported):
        raise MyException(f"Expected {len(supported)} GPUs for HAL method '{method}' in "
                          f"{c_filename} but found {len(field)}")

    return field

# When every implementation is an inline constant, the dispatch is enough to recover the
# value the method returns on each chip.  Return a dictionary mapping every GPU in
# `supported` to that value, or an empty dictionary if the method is not halified here.
def parse_nvoc_hal_method(c_filename: str, h_filename: str, method: str) -> dict:
    if not os.path.exists(h_filename):
        return {}

    dispatch = parse_nvoc_hal_dispatch(c_filename, method)
    if not dispatch:
        return {}

    bodies = nvoc_inline_bodies(h_filename)

    def value_of(implementation: str) -> int | bool:
        if implementation not in bodies:
            raise MyException(f"HAL method '{method}' in {c_filename} dispatches to "
                              f"{implementation}, which is not an inline constant in {h_filename}")
        return parse_c_value(bodies[implementation])

    return {gpu: value_of(implementation) for gpu, implementation in dispatch.items()}

# Look up the value of a HAL field for one GPU.
def hal_value(field: str, gpu: str) -> int | bool:
    if field not in hals:
        raise MyException(f"HAL field '{field}' is not defined")

    values = hals[field]

    if gpu in values:
        return values[gpu]

    raise MyException(f"HAL field '{field}' has no value for {gpu} and no default")

# Write a dictionary of HAL variables to nvoc-<version>.txt as an ASCII table, one column
# per variable and one row per GPU.  Values print as hexadecimal, except for the booleans
# some NVOC fields hold, which print as True / False because 0x1 would be needlessly
# cryptic.  A variable that has no value for a GPU gets an empty cell.
def print_hals(hals2: dict):
    global outputpath
    global version

    fields = list(hals2)

    # Take the GPUs in the order they were added, which for a fully initialized table is
    # the order of `supported`.  A variable is not required to cover every GPU.
    gpus = list(dict.fromkeys(gpu for values in hals2.values() for gpu in values))

    def cell(field: str, gpu: str) -> str:
        if gpu not in hals2[field]:
            return ""
        value = hals2[field][gpu]
        return str(value) if isinstance(value, bool) else f"0x{value:X}"

    headings = ["GPU"] + fields
    rows = [[gpu] + [cell(field, gpu) for field in fields] for gpu in gpus]

    # Size every column to its widest entry, heading included.
    widths = [max(len(row[column]) for row in [headings] + rows)
              for column in range(len(headings))]

    # GPU names read better left-aligned, numbers right-aligned.
    def line(cells: list) -> str:
        padded = [cells[0].ljust(widths[0])]
        padded += [cell.rjust(width) for cell, width in zip(cells[1:], widths[1:])]
        return "| " + " | ".join(padded) + " |"

    rule = "+" + "+".join("-" * (width + 2) for width in widths) + "+"

    filename = f"nvoc-{version}.txt"
    print(f"Creating {filename}")

    with open(os.path.join(tempfile.gettempdir(), filename), "w") as f:
        print(f"GSP-RM version {version}", file = f)
        print("\n".join([rule, line(headings), rule] + [line(row) for row in rows] + [rule]),
              file = f)

# RM headers guard many of their constants with "#if" blocks that select between build
# configurations, so a header is read by running it through pcpp's C preprocessor rather
# than by pattern matching its text.  The preprocessor evaluates those conditionals the way
# a compiler does, so only the definitions from the branch that is actually taken survive.
class HeaderPreprocessor(Preprocessor):
    # Headers that are not on the search path are dropped rather than reported as errors,
    # because most of what an RM header includes is irrelevant here.  The macros such a
    # header would have defined are then simply undefined, and since an undefined name
    # evaluates to 0 in an "#if", the result is the branch that a build with the feature
    # turned off would take.
    def on_include_not_found(self, is_malformed, is_system_include, curdir, includepath):
        raise OutputDirective(Action.IgnoreAndRemove)

    # The default prints to stderr and keeps going with a bad parse.
    def on_error(self, file, line, msg):
        raise MyException(f"{file}:{line}: {msg}")

# Headers that have already been preprocessed, keyed by file name, so that the repeated
# lookups parse_legacy_hals() makes in one header only preprocess it once.
preprocessed_headers = {}

# Preprocess a header and return the Preprocessor, whose "macros" dictionary then holds
# every macro that is still defined at the end of the file.
def preprocess_header(filename: str) -> Preprocessor:
    if filename in preprocessed_headers:
        return preprocessed_headers[filename]

    pp = HeaderPreprocessor()

    # RM headers include each other relative to these two directories.  Resolving those
    # includes is what gives a conditional such as "#if RMCFG_FEATURE_GSPRM_BULLSEYE" the
    # value the driver was configured with instead of the assumed default of 0.
    pp.add_path("src/nvidia/generated")
    pp.add_path("src/nvidia/inc")

    with open(filename) as f:
        pp.parse(f.read(), filename)

    # parse() only sets up the token stream.  The directives in it are executed as the
    # stream is consumed, so it has to be drained before "macros" is complete.  The
    # preprocessed text itself is of no interest.
    while pp.token():
        pass

    preprocessed_headers[filename] = pp
    return pp

# Look up an object-like "#define <macro> <expression>" in a C header and return the
# evaluated expression.  Definitions are often annotated with a trailing comment, as in
#
#   #define GSP_FW_HEAP_PARAM_BASE_RM_SIZE_GR10X              (32 << 20)   // GR10X+
#
# and long ones are continued across lines with a trailing backslash.  The preprocessor
# strips both, so the body reaches parse_c_value() as a bare expression.
#
# A definition may also name other macros, as in
#
#   #define GSP_FW_HEAP_PARAM_MAX_SUPPORTED_CHANNELS  2048   // Support 2048 channels
#   #define GSP_FW_HEAP_PARAM_CLIENT_ALLOC_SIZE      ((48 << 10) * GSP_FW_HEAP_PARAM_MAX_SUPPORTED_CHANNELS)
#
# Those names are expanded down to a literal expression first, so lookups can be made in
# any order, and an older header that spells the same value out in full needs no special
# handling.
def macro_value(filename: str, macro: str, fallback: str = None) -> int | bool:
    pp = preprocess_header(filename)

    if macro not in pp.macros and fallback:
        macro = fallback

    if macro not in pp.macros:
        raise MyException(f"Could not find {macro} in {filename}")

    definition = pp.macros[macro]

    # Only object-like macros have a value that can stand on its own.
    if definition.arglist is not None:
        raise MyException(f"{macro} in {filename} is a function-like macro")

    # expand_macros() rewrites the tokens it is handed in place, so give it copies and
    # leave the stored definition intact for the next lookup.
    body = pp.expand_macros([copy.copy(token) for token in definition.value])

    return parse_c_value("".join(token.value for token in body))

# Return the body of a hand-written function, or None if this source tree does not have
# the function at all.  The closing brace of a top-level function is the first one in
# column zero, so the body ends at the first "\n}".
def function_body(filename: str, function: str) -> str | None:
    with open(filename) as f:
        text = f.read()

    body = re.search(rf"{function}\s*\([^)]*\)\s*\{{(.*?)\n\}}", text, re.DOTALL)

    return body.group(1) if body else None

# Bodies already located by hal_implementation_body(), so that looking up the same
# implementation for a second WPR meta field does not walk the directory again.
hal_implementation_cache = {}

# Same, for a chip-specific HAL implementation, which unlike an _IMPL function can live in
# any of the per-architecture files under an engine's source directory.
def hal_implementation_body(directory: str, implementation: str) -> str | None:
    if (directory, implementation) in hal_implementation_cache:
        return hal_implementation_cache[(directory, implementation)]

    body = None
    for filename in glob.glob(os.path.join(directory, "**", "*.c"), recursive = True):
        body = function_body(filename, implementation)
        if body is not None:
            break

    hal_implementation_cache[(directory, implementation)] = body
    return body

# Older source trees compute part of the PMU reservation in hand-written code instead of
# in a HAL, so the only place the constant appears is the body of the _IMPL function:
#
#   NvU32 kpmuReservedMemoryMiscSizeGet_IMPL(KernelPmu *pKernelPmu)
#   {
#       if (kpmuGetIsSelfInit(pKernelPmu))
#       {
#           return (4U * (1U << 10U));
#       }
#
#       return 0U;
#   }
#
# These functions all return their constant from the first return statement and zero from
# the last, so take the first one.
def first_return_value(filename: str, function: str) -> int:
    body = function_body(filename, f"{function}_IMPL")
    if body is None:
        raise MyException(f"Could not find {function}_IMPL in {filename}")

    value = re.search(r"return\s+([^;]+);", body)
    if not value:
        raise MyException(f"{function}_IMPL in {filename} has no return statement")

    return parse_c_value(value.group(1))

# Calculate gspFwHeapBaseSize for each GPU:
#
#   carveout_size + base_rm_size + round_up(client_alloc_size + per_channel_size, 1MB)
#
# carveout_size is the LIBOS2 or LIBOS3 OS size depending on which one the chip runs,
# base_rm_size is the per-chip fwHeapParamBaseSize HAL, client_alloc_size is the client
# allocation, and per_channel_size is the per-chip overhead that r620 added, multiplied by
# the number of channels the heap is sized for.  RM rounds the last two terms up to a
# megabyte together rather than one at a time, so they are summed before rounding.
def parse_gsp_fw_heap_base_size() -> dict:
    macro_file = "src/nvidia/inc/kernel/gpu/gsp/gsp_fw_heap.h"

    # Contains the fwHeapParamBaseSize and fwHeapParamPerChannelOverhead variables
    kernel_gsp_nvoc = parse_nvoc_hals("src/nvidia/generated/g_kernel_gsp_nvoc.c",
                                      ["fwHeapParamBaseSize", "fwHeapParamPerChannelOverhead"])

    # Turing and GA100 use LIBOS2, all others use LIBOS3
    GSP_FW_HEAP_PARAM_OS_SIZE_LIBOS2 = macro_value(macro_file, "GSP_FW_HEAP_PARAM_OS_SIZE_LIBOS2")
    GSP_FW_HEAP_PARAM_OS_SIZE_LIBOS3_BAREMETAL = macro_value(macro_file, "GSP_FW_HEAP_PARAM_OS_SIZE_LIBOS3_BAREMETAL")

    # In some versions of OpenRM, GSP_FW_HEAP_PARAM_CLIENT_ALLOC_SIZE references
    # GSP_FW_HEAP_PARAM_MAX_SUPPORTED_CHANNELS, which macro_value() expands for us.
    GSP_FW_HEAP_PARAM_CLIENT_ALLOC_SIZE = macro_value(macro_file, "GSP_FW_HEAP_PARAM_CLIENT_ALLOC_SIZE")

    # r620 and later declare a per-channel overhead, and spell out the channel count that
    # it is charged for.  r615 has neither, which is the same arithmetic with an overhead
    # of zero, so one expression covers every release.
    per_channel_overhead = kernel_gsp_nvoc.get("fwHeapParamPerChannelOverhead", {})
    channels = (macro_value(macro_file, "GSP_FW_HEAP_PARAM_MAX_SUPPORTED_CHANNELS")
                if per_channel_overhead else 0)

    libos2_gpus = ["tu102", "tu104", "tu106", "tu116", "tu117", "ga100"]

    gspFwHeapBaseSize = {}

    for gpu in supported:
        carveout_size = (GSP_FW_HEAP_PARAM_OS_SIZE_LIBOS2 if gpu in libos2_gpus
                         else GSP_FW_HEAP_PARAM_OS_SIZE_LIBOS3_BAREMETAL)
        base_rm_size = kernel_gsp_nvoc["fwHeapParamBaseSize"][gpu]
        per_channel_size = per_channel_overhead.get(gpu, 0) * channels

        gspFwHeapBaseSize[gpu] = carveout_size + base_rm_size + round_up_to_base(
            GSP_FW_HEAP_PARAM_CLIENT_ALLOC_SIZE + per_channel_size, 1048576)

    return gspFwHeapBaseSize

# Calculate gspFwHeapSizePerGb for each GPU.  This one does not vary by chip, so the
# single macro applies to every GPU.
def parse_gsp_fw_heap_size_per_gb() -> dict:
    macro_file = "src/nvidia/inc/kernel/gpu/gsp/gsp_fw_heap.h"

    # Older versions of OpenRM called this GSP_FW_HEAP_PARAM_SIZE_PER_GB_FB.
    GSP_FW_HEAP_PARAM_SIZE_PER_GB = macro_value(macro_file, "GSP_FW_HEAP_PARAM_SIZE_PER_GB", "GSP_FW_HEAP_PARAM_SIZE_PER_GB_FB")

    gspFwHeapSizePerGb = {}

    for gpu in supported:
        gspFwHeapSizePerGb[gpu] = GSP_FW_HEAP_PARAM_SIZE_PER_GB

    return gspFwHeapSizePerGb

# Calculate gspFwHeapBaseSizeVgpu for each GPU.  OpenRM sizes the vGPU heap by how many
# VMs the chip supports, so gb202 takes the 48-VM value and gr10x the 7-VM value.  Older
# versions define only GSP_FW_HEAP_SIZE_VGPU_DEFAULT, which then stands in for both.
def parse_gsp_fw_heap_base_size_vgpu() -> dict:
    macro_file = "src/nvidia/inc/kernel/gpu/gsp/gsp_fw_heap.h"

    GSP_FW_HEAP_SIZE_VGPU_DEFAULT = macro_value(macro_file, "GSP_FW_HEAP_SIZE_VGPU_DEFAULT")

    # Older versions of OpenRM only defined GSP_FW_HEAP_SIZE_VGPU_DEFAULT
    GSP_FW_HEAP_SIZE_VGPU_7VMS = macro_value(macro_file, "GSP_FW_HEAP_SIZE_VGPU_7VMS", "GSP_FW_HEAP_SIZE_VGPU_DEFAULT")
    GSP_FW_HEAP_SIZE_VGPU_48VMS = macro_value(macro_file, "GSP_FW_HEAP_SIZE_VGPU_48VMS", "GSP_FW_HEAP_SIZE_VGPU_DEFAULT")

    # Simple sanity check
    if GSP_FW_HEAP_SIZE_VGPU_48VMS < GSP_FW_HEAP_SIZE_VGPU_7VMS:
        raise MyException(f"Invalid values for {GSP_FW_HEAP_SIZE_VGPU_7VMS=} and {GSP_FW_HEAP_SIZE_VGPU_48VMS=}")

    gspFwHeapBaseSizeVgpu = {}

    for gpu in supported:
        if gpu == "gb202":
            gspFwHeapBaseSizeVgpu[gpu] = GSP_FW_HEAP_SIZE_VGPU_48VMS
        elif gpu.startswith("gr"):
            gspFwHeapBaseSizeVgpu[gpu] = GSP_FW_HEAP_SIZE_VGPU_7VMS
        else:
            # Unlike OpenRM, Nova only supports vGPU on Blackwell and later, so
            # pre-Blackwell will never actually use gspFwHeapBaseSizeVgpu or
            # gspFwHeapSizePerVm.
            gspFwHeapBaseSizeVgpu[gpu] = GSP_FW_HEAP_SIZE_VGPU_DEFAULT

    return gspFwHeapBaseSizeVgpu

# Calculate gspFwHeapSizePerVm for each GPU.  This is zero everywhere for now, because the
# per-VM cost is still bundled into gspFwHeapBaseSizeVgpu; a future version of OpenRM will
# reduce that base and set this one properly.  Returning an empty dictionary leaves the
# zero-filling to parse_legacy_hals().
def parse_gsp_fw_heap_size_per_vm() -> dict:
    return {}

# kgspPopulateWprMeta_GH100() works out the WPR layout, but a chip whose HAL is layered on
# top of that one can overwrite individual fields afterwards.  The iGPUs do exactly that:
#
#   // Layout is close to GH100, so use that HAL first then override as necessary
#   NV_ASSERT_OK_OR_RETURN(kgspPopulateWprMeta_GH100(pGpu, pKernelGsp, pGspFw));
#   ...
#   pWprMeta->pmuReservedSize = 0; // No PMU Reserved memory in GB10B
#   ...
#   pWprMeta->nonWprHeapSize = 0;
#
# so whatever RM computed for those fields never reaches the WPR meta on an iGPU.  Zero the
# GPUs whose implementation assigns 0 to 'field', which is the WPR meta member that the
# values being passed in feed.  Matching on the assignment rather than on the name of the
# implementation picks up any future chip that does the same thing.
def apply_wpr_meta_override(field: str, values: dict) -> dict:
    dispatch = parse_nvoc_hal_dispatch("src/nvidia/generated/g_kernel_gsp_nvoc.c",
                                       "kgspPopulateWprMeta")

    zeroed = {}
    for implementation in set(dispatch.values()):
        body = hal_implementation_body("src/nvidia/src/kernel/gpu/gsp", implementation)
        zeroed[implementation] = bool(
            body and re.search(rf"pWprMeta->{field}\s*=\s*0\s*;", body))

    return {gpu: 0 if zeroed.get(dispatch.get(gpu)) else value
            for gpu, value in values.items()}

# Calculate what kpmuReservedMemorySizeGet() returns for each GPU.  The value is never
# spelled out in the source, so it has to be rebuilt from the terms RM sums, and those
# terms have been rearranged twice:
#
#   r570: ALIGN_UP(backing store + surfaces + misc), where the surfaces size
#         is one PMU_RESERVED_MEMORY_SURFACES_SIZE macro for every chip.
#   r615: the same sum, but the surfaces size became a per-chip HAL.
#   r620: ALIGN_UP(backing store), which is itself now a per-chip HAL, with
#         surfaces and misc moved out to the non-WPR carveout that
#         gpuGetPmuReservedMemoryNonWprSize() sizes.
#
# In both of the older shapes every term is zero unless the chip reports itself as "self
# init", and the backing store and misc sizes are literals in hand-written code.
def parse_pmu_reserved_size() -> dict:
    kern_pmu_c = "src/nvidia/generated/g_kern_pmu_nvoc.c"
    kern_pmu_h = "src/nvidia/generated/g_kern_pmu_nvoc.h"
    kern_pmu = "src/nvidia/src/kernel/gpu/pmu/kern_pmu.c"

    if not os.path.exists(kern_pmu_h):
        raise MyException(f"Could not find {kern_pmu_h}")

    alignment = macro_value(kern_pmu_h, "KPMU_RESERVED_MEMORY_ALIGNMENT")

    # r620 and later.  Everything needed is in the generated files.
    backing = parse_nvoc_hal_method(kern_pmu_c, kern_pmu_h,
                                    "kpmuReservedMemoryBackingStoreSizeGet")
    if backing:
        pmuReservedSize = {gpu: round_up_to_base(backing[gpu], alignment)
                           for gpu in supported}
        return apply_wpr_meta_override("pmuReservedSize", pmuReservedSize)

    self_init = parse_nvoc_hal_method(kern_pmu_c, kern_pmu_h, "kpmuGetIsSelfInit")
    if not self_init:
        raise MyException(f"Neither kpmuReservedMemoryBackingStoreSizeGet nor "
                          f"kpmuGetIsSelfInit is halified in {kern_pmu_c}")

    backing_size = first_return_value(kern_pmu, "kpmuReservedMemoryBackingStoreSizeGet")
    misc_size = first_return_value(kern_pmu, "kpmuReservedMemoryMiscSizeGet")

    surfaces = parse_nvoc_hal_method("src/nvidia/generated/g_gpu_nvoc.c",
                                     "src/nvidia/generated/g_gpu_nvoc.h",
                                     "gpuGetPmuReservedMemorySurfacesSize")
    if not surfaces:
        surfaces_size = macro_value(kern_pmu_h, "PMU_RESERVED_MEMORY_SURFACES_SIZE")
        surfaces = {gpu: surfaces_size for gpu in supported}

    pmuReservedSize = {gpu: round_up_to_base(backing_size + surfaces[gpu] + misc_size,
                                             alignment) if self_init[gpu] else 0
                       for gpu in supported}

    return apply_wpr_meta_override("pmuReservedSize", pmuReservedSize)

# Calculate what gpuGetPmuReservedMemoryNonWprSize() returns for each GPU.  r620 moved the
# surfaces and misc terms out of the WPR reservation that kpmuReservedMemorySizeGet()
# reports and into the non-WPR GSP carveout, where they are summed with no alignment of
# their own:
#
#   NvU32 gpuGetPmuReservedMemoryNonWprSize_IMPL(OBJGPU *pGpu)
#   {
#       return (gpuGetPmuReservedMemorySurfacesSize(pGpu) +
#               gpuGetPmuReservedMemoryMiscSize(pGpu));
#   }
#
# Older trees make no such split -- the whole reservation lives inside WPR -- so every GPU
# is zero on them.
#
# Nova adds this to the GSP's own portion to size the carveout, the same way RM does in
# kgspGetNonWprHeapSize(), and that sum is what lands in the WPR meta as nonWprHeapSize.
# So the iGPUs, which zero nonWprHeapSize outright, contribute nothing here either.
def parse_pmu_non_wpr_reserved_size() -> dict:
    gpu_c = "src/nvidia/generated/g_gpu_nvoc.c"
    gpu_h = "src/nvidia/generated/g_gpu_nvoc.h"
    gpu_source = "src/nvidia/src/kernel/gpu/gpu.c"

    body = function_body(gpu_source, "gpuGetPmuReservedMemoryNonWprSize_IMPL")
    if body is None:
        return {gpu: 0 for gpu in supported}

    # Both terms are per-chip HALs.  Anything else in the sum is a term this code does
    # not know how to evaluate, so refuse to guess.
    terms = set(re.findall(r"(gpu\w+)\s*\(pGpu\)", body))
    expected = {"gpuGetPmuReservedMemorySurfacesSize", "gpuGetPmuReservedMemoryMiscSize"}
    if terms != expected:
        raise MyException(f"gpuGetPmuReservedMemoryNonWprSize_IMPL in {gpu_source} sums "
                          f"{sorted(terms)}, expected {sorted(expected)}")

    surfaces = parse_nvoc_hal_method(gpu_c, gpu_h, "gpuGetPmuReservedMemorySurfacesSize")
    misc = parse_nvoc_hal_method(gpu_c, gpu_h, "gpuGetPmuReservedMemoryMiscSize")
    if not surfaces or not misc:
        raise MyException(f"gpuGetPmuReservedMemoryNonWprSize_IMPL exists in {gpu_source} "
                          f"but its terms are not halified in {gpu_c}")

    pmuNonWprReservedSize = {gpu: surfaces[gpu] + misc[gpu] for gpu in supported}

    return apply_wpr_meta_override("nonWprHeapSize", pmuNonWprReservedSize)

# Build the HAL table for a source tree whose g_gpu_arch_nvoc.c does not carry these
# values, which is still the case for every release through r620.  Each variable is
# reconstructed by its own function, from whatever gsp_fw_heap.h, the NVOC-generated files
# and the hand-written sources happen to spell out in that particular release.  A function
# that returns a partial dictionary has its remaining GPUs zero-filled here.
def parse_legacy_hals():
    hals2 = {
        "gspFwHeapBaseSize": parse_gsp_fw_heap_base_size(),
        "gspFwHeapSizePerGb": parse_gsp_fw_heap_size_per_gb(),
        "gspFwHeapBaseSizeVgpu": parse_gsp_fw_heap_base_size_vgpu(),
        "gspFwHeapSizePerVm": parse_gsp_fw_heap_size_per_vm(),
        "pmuReservedSize": parse_pmu_reserved_size(),
        "pmuNonWprReservedSize": parse_pmu_non_wpr_reserved_size(),
    }

    for hal in hals2:
        for gpu in supported:
            hals2[hal].setdefault(gpu, 0)

    return hals2

# Perform a deep merge of a partial HAL dictionary into the global variable hals{}.
# GPUs that are not in `supported` are dropped.
def update_hals(update: dict):
    global hals

    for field, values in update.items():
        hals.setdefault(field, {}).update(
            {gpu: value for gpu, value in values.items() if gpu in supported})

